// Screen navigator engine (docs/navigator-copilot-plan.md). Streaming multimodal
// chat over OpenAI-compatible chat completions so the same code path serves
// both vendors: the auto first turn (scene recognition one-liner) prefers the
// fast vendor (Groq llama-4), follow-up navigation turns use the main model.
// Output is plain text, not JSON — nothing to parse means the first token is
// the first visible character.

import { getServerEnv } from "@/lib/server/env";
import { ProviderCallError } from "@/lib/server/review-engine";
import type { VisionObservation } from "@/lib/context/observation";
import {
  selectHarness,
  type Harness,
  type NavigateHints,
  type Recipe,
} from "@/lib/server/harness";
import type { OutputLanguageCode } from "@/lib/server/prompts";
import {
  groundObservationCandidate,
  type CandidateGrounding,
  type GrounderExecution,
} from "@/lib/server/navigate-grounder";

const VENDOR_ENDPOINTS: Record<string, string> = {
  groq: "https://api.groq.com/openai/v1/chat/completions",
  openai: "https://api.openai.com/v1/chat/completions",
  // Gemini via its OpenAI-compatible layer. Candidate for the navigator:
  // Gemini is natively trained to emit bounding boxes on a 0-1000 grid, so
  // its [[loc:…]] should be tighter. Switch with the BOMB_SQUAD_NAVIGATE_*
  // env vars once GEMINI_API_KEY is configured.
  gemini: "https://generativelanguage.googleapis.com/v1beta/openai/chat/completions",
};

const LANGUAGE_PROMPT_NAMES: Record<OutputLanguageCode, string> = {
  japanese: "日本語",
  english: "英語",
};

export type NavigateMessage = {
  role: "user" | "assistant";
  text?: string;
  imageDataURL?: string;
  ocrText?: string;
  /** Versioned capture snapshot. Accepted and traced in v4 shadow mode;
   * provider prompting still follows the v3 image/OCR contract for now. */
  observation?: VisionObservation;
};

export type NavigateTaskStep = {
  verbal: string;
  target?: string;
  fill?: string;
};

/** The session's plan (docs/navigator-copilot-plan.md §3-a). Created once by
 * the planner, then held by the CLIENT and re-sent with every request — the
 * gateway stays stateless. `currentStep` advances client-side on the
 * [[step:done]] marker. */
export type NavigateTask = {
  goal: string;
  steps: NavigateTaskStep[];
  currentStep: number;
};

export type NavigateEngineInput = {
  messages: NavigateMessage[];
  hints?: NavigateHints;
  language: OutputLanguageCode;
  task?: NavigateTask;
};

export type NavigateEngineOutput = {
  text: string;
  harnessId: string | null;
  modelVendor: string;
  modelId: string;
  inputTokens: number;
  outputTokens: number;
  /** Whether the final text carries a [[target/loc]] marker (metric seed). */
  hasLocator: boolean;
  /** Whether the marker came from the enforcement supplement call. */
  locatorSupplemented: boolean;
  /** Additive v4 shadow result. The v3 marker path remains authoritative. */
  grounding: CandidateGrounding | null;
  groundingAttempted: boolean;
  groundingInputTokens: number;
  groundingOutputTokens: number;
  /** Task generated by the planner this turn (null: none was attempted or
   * the question wasn't a plannable multi-step goal). */
  proposedTask: NavigateTask | null;
};

export type NavigateStreamEvent =
  | { type: "delta"; text: string }
  | { type: "final"; output: NavigateEngineOutput };

/** The auto first turn carries a screenshot but no user question. */
export function isAutoFirstTurn(messages: NavigateMessage[]): boolean {
  const last = messages[messages.length - 1];
  return (
    messages.length === 1 &&
    last.role === "user" &&
    !last.text?.trim() &&
    Boolean(last.imageDataURL)
  );
}

export async function* runNavigateStream(
  input: NavigateEngineInput,
): AsyncGenerator<NavigateStreamEvent> {
  const env = getServerEnv();
  const firstTurn = isAutoFirstTurn(input.messages);

  // Vendor staging: fast model for the first-turn one-liner when its key is
  // configured, main model otherwise and for every follow-up turn.
  let vendor = firstTurn ? env.navigateFastModelVendor : env.navigateModelVendor;
  let modelId = firstTurn ? env.navigateFastModelId : env.navigateModelId;
  if (!apiKeyFor(vendor)) {
    vendor = env.navigateModelVendor;
    modelId = env.navigateModelId;
  }
  const apiKey = apiKeyFor(vendor);
  const endpoint = VENDOR_ENDPOINTS[vendor];
  if (!apiKey || !endpoint) {
    throw new ProviderCallError(`No provider key configured for vendor "${vendor}".`);
  }

  // Data-driven packs with the in-code seed as fallback (foundation-redesign
  // §5-b); matching semantics are unchanged, loading is now async + cached.
  const harness = await selectHarness(input.hints);

  // Planner (docs/navigator-copilot-plan.md §3-a): a question turn on a
  // harness-known tool with no active task gets one concurrent structured
  // call that tries to turn the question into a step plan. It never blocks
  // the streamed answer — its result rides on the final event only.
  const lastMessage = input.messages[input.messages.length - 1];
  const shouldPlan =
    !firstTurn &&
    !input.task &&
    Boolean(harness?.recipes?.length) &&
    Boolean(lastMessage.text?.trim());
  const plannerPromise = shouldPlan
    ? planTask({
        endpoint,
        apiKey,
        modelId,
        recipes: harness!.recipes!,
        question: lastMessage.text!.trim(),
        imageDataURL: latestImage(input.messages),
        ocrText: latestOCR(input.messages),
        language: input.language,
      }).catch(() => null)
    : Promise.resolve(null);

  const providerMessages: Array<Record<string, unknown>> = [
    { role: "system", content: systemPrompt(input.language, harness, input.hints, input.task) },
    ...input.messages.map((message, index) =>
      providerMessage(message, index === 0, input.messages.length === 1),
    ),
  ];
  const body: Record<string, unknown> = {
    model: modelId,
    // The first turn is contractually one sentence; navigation answers are
    // short by design (one step at a time). `max_completion_tokens` is the
    // only cap OpenAI gpt-5 models accept (`max_tokens` is rejected with a
    // 400); Groq accepts it too, so both vendors share it.
    max_completion_tokens: firstTurn ? 400 : 1200,
    stream: true,
    stream_options: { include_usage: true },
    messages: providerMessages,
  };

  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "content-type": "application/json",
    },
    body: JSON.stringify(body),
  });

  if (response.status === 429) {
    throw new ProviderCallError(
      "AI エンジンが混雑しています。数秒おいてから再試行してください。",
      { rateLimited: true },
    );
  }
  if (!response.ok || !response.body) {
    const detail = (await response.text()).slice(0, 500);
    throw new ProviderCallError(`Provider HTTP ${response.status}: ${detail}`);
  }

  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let fullText = "";
  let sseBuffer = "";
  let inputTokens = 0;
  let outputTokens = 0;

  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      sseBuffer += decoder.decode(value, { stream: true });

      const lines = sseBuffer.split("\n");
      sseBuffer = lines.pop() ?? "";
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed.startsWith("data:")) continue;
        const payload = trimmed.slice(5).trim();
        if (payload === "[DONE]") continue;

        let chunk: {
          choices?: Array<{ delta?: { content?: string } }>;
          usage?: { prompt_tokens?: number; completion_tokens?: number } | null;
          x_groq?: { usage?: { prompt_tokens?: number; completion_tokens?: number } };
        };
        try {
          chunk = JSON.parse(payload);
        } catch {
          continue;
        }

        const usage = chunk.usage ?? chunk.x_groq?.usage;
        if (usage) {
          inputTokens = usage.prompt_tokens ?? inputTokens;
          outputTokens = usage.completion_tokens ?? outputTokens;
        }

        const content = chunk.choices?.[0]?.delta?.content;
        if (typeof content === "string" && content.length > 0) {
          fullText += content;
          yield { type: "delta", text: content };
        }
      }
    }
  } finally {
    reader.releaseLock();
  }

  if (!fullText.trim()) {
    throw new ProviderCallError("Provider stream ended without content.");
  }

  // Rule-based marker enforcement (docs/navigator-copilot-plan.md §2-c): a
  // navigation answer without a locator gets one small follow-up call asking
  // only for the [[target:…]] of whatever the answer pointed at. The client
  // strips markers from the streamed display, so the appended delta is
  // invisible text-wise and only surfaces as the highlight. Best-effort: a
  // failed supplement never fails the turn.
  let locatorSupplemented = false;
  if (!firstTurn && !LOCATOR_MARKER.test(fullText)) {
    try {
      const supplement = await fetchLocatorSupplement({
        endpoint,
        apiKey,
        modelId,
        providerMessages,
        answerText: fullText,
      });
      if (supplement) {
        const addition = ` ${supplement.marker}`;
        fullText += addition;
        inputTokens += supplement.inputTokens;
        outputTokens += supplement.outputTokens;
        locatorSupplemented = true;
        yield { type: "delta", text: addition };
      }
    } catch {
      // Ignore: the verbal answer already streamed; only the highlight is lost.
    }
  }

  let grounding: GrounderExecution = {
    attempted: false,
    selection: null,
    inputTokens: 0,
    outputTokens: 0,
  };
  const observation = latestObservation(input.messages);
  const targetLabel = groundingTarget(input.task, fullText);
  if (env.navigateV4Enabled && !firstTurn && observation && targetLabel) {
    try {
      grounding = await groundObservationCandidate({
        endpoint,
        apiKey,
        modelId,
        observation,
        targetLabel,
        context: groundingContext(input, fullText),
      });
      inputTokens += grounding.inputTokens;
      outputTokens += grounding.outputTokens;
    } catch {
      grounding = { ...grounding, attempted: true };
    }
  }

  yield {
    type: "final",
    output: {
      text: fullText,
      harnessId: harness?.id ?? null,
      modelVendor: vendor,
      modelId,
      inputTokens,
      outputTokens,
      hasLocator: LOCATOR_MARKER.test(fullText),
      locatorSupplemented,
      grounding: grounding.selection,
      groundingAttempted: grounding.attempted,
      groundingInputTokens: grounding.inputTokens,
      groundingOutputTokens: grounding.outputTokens,
      proposedTask: await plannerPromise,
    },
  };
}

function latestImage(messages: NavigateMessage[]): string | undefined {
  for (let i = messages.length - 1; i >= 0; i--) {
    if (messages[i].imageDataURL) return messages[i].imageDataURL;
  }
  return undefined;
}

function latestOCR(messages: NavigateMessage[]): string | undefined {
  for (let i = messages.length - 1; i >= 0; i--) {
    const ocr = messages[i].ocrText?.trim();
    if (ocr) return ocr;
  }
  return undefined;
}

function latestObservation(messages: NavigateMessage[]): VisionObservation | undefined {
  for (let i = messages.length - 1; i >= 0; i--) {
    if (messages[i].observation) return messages[i].observation;
  }
  return undefined;
}

function groundingTarget(task: NavigateTask | undefined, answer: string): string | null {
  const stepTarget = task?.steps[task.currentStep]?.target?.trim();
  if (stepTarget) return stepTarget;
  return answer.match(/\[\[target:([^\]]{1,120})\]\]/)?.[1]?.trim() ?? null;
}

function groundingContext(input: NavigateEngineInput, answer: string): string {
  const question = [...input.messages].reverse().find((message) => message.text?.trim())?.text;
  const step = input.task?.steps[input.task.currentStep];
  return [
    question ? `User request: ${question}` : null,
    input.task ? `Task goal: ${input.task.goal}` : null,
    step ? `Current step: ${step.verbal}` : null,
    `Navigator answer: ${answer}`,
  ].filter(Boolean).join("\n");
}

// Matches any complete locator marker. Deliberately un-anchored and without
// the `g` flag: `.test` must stay stateless across calls.
const LOCATOR_MARKER = /\[\[(?:target|loc):[^\]]+\]\]/;

const LOCATOR_SUPPLEMENT_INSTRUCTION = `あなたの直前の回答が、ユーザーの画面上に見えている要素（ボタン・メニュー・リンク・入力欄など）を指しているなら、その要素に実際に表示されている文字列を [[target:表示文字列]] の形式で1つだけ出力してください（翻訳・言い換えをしない）。回答が画面内の要素を指していない場合（対象が画面に見えていない・一般的な説明のみ）は NONE とだけ出力してください。それ以外の文章は出力しないでください。`;

